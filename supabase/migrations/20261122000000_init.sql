-- Migration: Initial Schema for Notes App
-- NOTE: Intentionally missing Row Level Security (RLS) to test SecondKey IDOR detection!

CREATE TABLE IF NOT EXISTS public.notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- RLS is explicitly disabled, allowing anyone with the anon key to read all private notes
ALTER TABLE public.notes DISABLE ROW LEVEL SECURITY;

